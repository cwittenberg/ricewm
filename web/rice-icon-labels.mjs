export function riceIconLabel(name) {
    const value = String(name);
    const colored = value.endsWith('-color');
    const base = colored ? value.slice(0, -6) : value;
    if (!Object.hasOwn(labels, base)) return value;
    const label = labels[base]();
    return colored ? t('icons.colored', {name: label}) : label;
}
